def is_han(ch):
    cp = ord(ch)
    return (0x4E00 <= cp <= 0x9FFF) or (0x3400 <= cp <= 0x4DBF) or (0xF900 <= cp <= 0xFAFF)


def han_chars_in(text):
    return {ch for ch in text if is_han(ch)}


def load_jieba_entries(path):
    entries = []
    with io.open(path, encoding="utf-8") as f:
        for line in f:
            line = line.rstrip("\n")
            if not line:
                continue
            parts = line.split(" ")
            word, freq_s = parts[0], parts[1]
            entries.append((word, int(freq_s)))
    return entries


def chinese_han_chars_at_threshold(entries, min_freq):
    chars = set()
    for word, freq in entries:
        if freq >= min_freq:
            chars.update(han_chars_in(word))
    return chars


def load_japanese_han_chars(path):
    chars = set()
    with io.open(path, encoding="utf-8") as f:
        for line in f:
            word = line.rstrip("\n")
            if not word:
                continue
            chars.update(han_chars_in(word))
    return chars


def parse_ja_only_hand_list(raw):
    tokens = raw.split()
    kept, dropped = [], []
    for tok in tokens:
        if len(tok) == 1 and is_han(tok):
            kept.append(tok)
        else:
            dropped.append(tok)
    return kept, dropped


def format_str_literal(name, chars_sorted, chunk_size=64, indent="    "):
    lines = [f"{name} = ("]
    if not chars_sorted:
        lines.append(f'{indent}""')
    else:
        for i in range(0, len(chars_sorted), chunk_size):
            chunk = chars_sorted[i:i + chunk_size]
            lines.append(f'{indent}"{chunk}"')
    lines.append(")")
    return "\n".join(lines)


def write_generated_file(path, zh_only_sorted, ja_only_sorted):
    docstring = (
        '"""\n'
        "Auto-generated by tools/build_cjk_tables.py. Do not hand-edit;\n"
        "re-run the generator instead.\n"
        "\n"
        "Source data:\n"
        "  ZH_ONLY_CHARS: characters used in Simplified Chinese (jieba\n"
        "    dict.txt) that never appear in the Japanese word list\n"
        "    (misaki ja_words.txt). Chinese side filtered to dictionary\n"
        f"    entries with frequency >= MIN_WORD_FREQ = {MIN_WORD_FREQ}.\n"
        "    Japanese side used in full, no frequency filter.\n"
        "  JA_ONLY_CHARS: a small hand-checked, hardcoded list of\n"
        "    characters that differ from BOTH Simplified and Traditional\n"
        "    Chinese forms. Not derived from data; see build_cjk_tables.py\n"
        "    for why.\n"
        "\n"
        f"Generated on: {date.today().isoformat()}\n"
        '"""\n'
    )
    body = (
        format_str_literal("ZH_ONLY_CHARS", zh_only_sorted)
        + "\n\n"
        + format_str_literal("JA_ONLY_CHARS", ja_only_sorted)
        + "\n"
    )
    with io.open(path, "w", encoding="utf-8", newline="\n") as f:
        f.write(docstring)
        f.write("\n")
        f.write(body)


