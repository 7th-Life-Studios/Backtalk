def run_spot_checks(zh_only, ja_only):
    results = []

    def check(label, chars, table, expect):
        for ch in chars:
            actual = ch in table
            ok = actual == expect
            results.append((label, ch, expect, actual, ok))

    check("ZH_ONLY expect YES", SPOT_ZH_ONLY_YES, zh_only, True)
    check("ZH_ONLY expect NO (traditional/japanese)", SPOT_ZH_ONLY_NO_TRADITIONAL_OR_JAPANESE, zh_only, False)
    check("ZH_ONLY expect NO (shared)", SPOT_ZH_ONLY_NO_SHARED, zh_only, False)
    check("JA_ONLY expect YES", SPOT_JA_ONLY_YES, ja_only, True)
    check("JA_ONLY expect NO", SPOT_JA_ONLY_NO, ja_only, False)
    return results


SANITY_SENTENCES = [
    "黑猫每天下午都在厨房的椅子上睡觉。",
    "会议在三点开始",
    "我们今天去学校学习中文。",
    "黒い猫は毎日午後に台所の椅子で寝ています。",
    "東京都庁舎",
    "会議",
]


def run_sanity_check(zh_only, ja_only):
    rows = []
    for sentence in SANITY_SENTENCES:
        han = [ch for ch in sentence if is_han(ch)]
        zh_hits = [ch for ch in han if ch in zh_only]
        ja_hits = [ch for ch in han if ch in ja_only]
        rows.append((sentence, len(han), zh_hits, ja_hits))
    return rows


def main():
    if not os.path.isfile(JIEBA_DICT_PATH):
        print("ERROR: jieba dict.txt not found at", JIEBA_DICT_PATH)
        sys.exit(1)
    if not os.path.isfile(JA_WORDS_PATH):
        print("ERROR: ja_words.txt not found at", JA_WORDS_PATH)
        sys.exit(1)

    entries = load_jieba_entries(JIEBA_DICT_PATH)
    print(f"jieba dict.txt: {len(entries)} entries loaded from {JIEBA_DICT_PATH}")

    print("\n--- Threshold sweep (Chinese Han char count) ---")
    threshold_sets = {}
    for t in REPORT_THRESHOLDS:
        s = chinese_han_chars_at_threshold(entries, t)
        threshold_sets[t] = s
        print(f"  MIN_WORD_FREQ >= {t:5d}: {len(s)} distinct Han characters")

    if MIN_WORD_FREQ in threshold_sets:
        chinese_chars = threshold_sets[MIN_WORD_FREQ]
    else:
        chinese_chars = chinese_han_chars_at_threshold(entries, MIN_WORD_FREQ)
        print(f"  MIN_WORD_FREQ >= {MIN_WORD_FREQ:5d}: {len(chinese_chars)} distinct Han characters (chosen)")

    japanese_chars = load_japanese_han_chars(JA_WORDS_PATH)
    print(f"\nja_words.txt: {len(japanese_chars)} distinct Han characters found (no filter, all entries used)")

    zh_only = chinese_chars - japanese_chars
    print(f"\nZH_ONLY = chinese_chars(MIN_WORD_FREQ={MIN_WORD_FREQ}) - japanese_chars = {len(zh_only)} characters")

    ja_only_candidates, dropped_tokens = parse_ja_only_hand_list(_JA_ONLY_HAND_CHECKED_RAW)
    print(f"\nJA_ONLY hand list: {len(ja_only_candidates)} character tokens, {len(dropped_tokens)} dropped token(s)")
    for tok in dropped_tokens:
        print(f"  DROPPED (not a single Han character): {tok!r}")
        if tok == "land":
            print("  -> caught the stray 'land' token as instructed, excluded it")

    collisions = [c for c in ja_only_candidates if c in chinese_chars]
    ja_only_final = [c for c in ja_only_candidates if c not in chinese_chars]
    print(f"\nJA_ONLY collision check against Chinese set (MIN_WORD_FREQ={MIN_WORD_FREQ}):")
    if collisions:
        print(f"  COLLISIONS FOUND, excluded from JA_ONLY: {' '.join(collisions)}")
    else:
        print("  none: every hand-checked character is clean of the Chinese set")
    print(f"JA_ONLY final count: {len(ja_only_final)}")

    zh_only_sorted = "".join(sorted(zh_only))
    ja_only_sorted = "".join(sorted(set(ja_only_final)))

    write_generated_file(OUTPUT_PATH, zh_only_sorted, ja_only_sorted)
    print(f"\nWrote {OUTPUT_PATH}")
    print(f"  ZH_ONLY_CHARS: {len(zh_only_sorted)} characters")
    print(f"  JA_ONLY_CHARS: {len(ja_only_sorted)} characters")

    print("\n--- Spot checks ---")
    spot_results = run_spot_checks(zh_only, set(ja_only_final))
    by_label = {}
    for label, ch, expect, actual, ok in spot_results:
        by_label.setdefault(label, []).append((ch, expect, actual, ok))
    for label, rows in by_label.items():
        n_pass = sum(1 for r in rows if r[3])
        print(f"{label}: {n_pass}/{len(rows)} PASS")
        for ch, expect, actual, ok in rows:
            if not ok:
                print(f"  FAIL char={ch!r} expected={expect} actual={actual}")

    print("\n--- Contradiction check between hand-written expected lists ---")
    yes_zh = set(SPOT_ZH_ONLY_YES)
    no_zh_trad = set(SPOT_ZH_ONLY_NO_TRADITIONAL_OR_JAPANESE)
    no_zh_shared = set(SPOT_ZH_ONLY_NO_SHARED)
    yes_ja = set(SPOT_JA_ONLY_YES)
    no_ja = set(SPOT_JA_ONLY_NO)

    def report_overlap(name_a, set_a, name_b, set_b, table, table_name):
        overlap = set_a & set_b
        if overlap:
            print(f"  CONTRADICTION between [{name_a}] and [{name_b}]: {' '.join(sorted(overlap))}")
            for ch in sorted(overlap):
                print(f"    measured: {ch!r} in {table_name} = {ch in table}")
        return overlap

    any_overlap = False
    for name_a, set_a, name_b, set_b, table, table_name in [
        ("ZH_ONLY expect YES", yes_zh, "ZH_ONLY expect NO (traditional/japanese)", no_zh_trad, zh_only, "ZH_ONLY"),
        ("ZH_ONLY expect YES", yes_zh, "ZH_ONLY expect NO (shared)", no_zh_shared, zh_only, "ZH_ONLY"),
        ("JA_ONLY expect YES", yes_ja, "JA_ONLY expect NO", no_ja, set(ja_only_final), "JA_ONLY"),
    ]:
        if report_overlap(name_a, set_a, name_b, set_b, table, table_name):
            any_overlap = True
    if not any_overlap:
        print("  none found")

    print("\n--- Frequency sanity check on real sentences ---")
    for sentence, han_count, zh_hits, ja_hits in run_sanity_check(zh_only, set(ja_only_final)):
        print(f"  {sentence!r}")
        print(f"    han_chars={han_count} zh_only={len(zh_hits)} ja_only={len(ja_hits)}")
        print(f"    zh_only chars: {''.join(zh_hits)!r}  ja_only chars: {''.join(ja_hits)!r}")


if __name__ == "__main__":
    main()
