ALL: list[str] = [phrase for group in CATEGORIES.values() for phrase in group]

_HISTORY_FILE = "phrase_history.json"


def _history_path():
    return config.DATA / _HISTORY_FILE


def _load_recent() -> list[str]:
    try:
        data = json.loads(_history_path().read_text(encoding="utf-8"))
        return [p for p in data if isinstance(p, str)] if isinstance(data, list) else []
    except (OSError, json.JSONDecodeError, ValueError):
        return []


def _save_recent(recent: list[str]) -> None:
    try:
        config.DATA.mkdir(parents=True, exist_ok=True)
        _history_path().write_text(json.dumps(recent), encoding="utf-8")
    except OSError:
        pass


def random_phrase() -> str:
    if not ALL:
        return ""
    recent = _load_recent()
    unused = [p for p in ALL if p not in set(recent)]
    if not unused:
        recent = []
        unused = list(ALL)
    choice = random.choice(unused)
    recent.append(choice)
    _save_recent(recent)
    return choice
